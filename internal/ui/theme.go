package ui

// Theme holds the MD3E tokens the whole UI draws with. The motion needed for a
// state change is expressed with spring presets, never with durations;
// colours here only ever change through spring-driven values in widgets.
type Theme struct {
	Bg         Color
	Surface    Color
	Surface2   Color
	Surface3   Color
	Outline    Color
	Outline2   Color
	Text       Color
	Muted      Color
	Primary    Color
	OnPrimary  Color
	PrimaryDim Color
	PrimaryBg  Color
	Tertiary   Color
	Danger     Color
	DangerBg   Color
	Success    Color
	SuccessBg  Color
	Warn       Color
	WarnBg     Color
	CardRadius float32
	PillRadius float32
	Style      string
	Dark       bool
	Advanced   bool
}

